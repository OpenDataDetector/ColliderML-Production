"""Generate the v23 ttbar configs (PU0 hard_scatter, PU200 full_pileup) from the v20/v22 ones.

v23 = v22 rerun from the tracking stage with (Daniel, 2026-11-21):
  * ACTS seed finder at the detector field (3 T) and seed-finder minPt 0.65 GeV
    (testbed/v23_plan/README.md sections 5, 5b);
  * the digitisation seed string of the version each run replaces (D2):
    PU0 runs 0-7 and PU200 runs 0-15 from v20, PU200 runs 16-1562 from v22;
  * AMVF primary vertexing, packaged as reco/vertices;
  * packaging: rows sorted by event_id (D3), n_shared_hits from hit_ids,
    generator_particles and vertices packaged, PU200 1000 chunks of 100 (events 0-99,999);
  * a provenance record per run and stage, commit must be on a pushed branch,
    .git_commit_success written by the packaging stage only;
  * all outputs under data/ColliderML/staging/simulation (VERIFICATION_PLAN_v3_1 II.0);
    publication is a later, separate rename.
Job sizing, images, events, threads and every other physics setting are copied from the parent.

Usage:
  python make_v23_configs.py                        # print what would be written
  python make_v23_configs.py --apply                # write configs_production/*/ttbar/v23/
  python make_v23_configs.py --apply --base DIR --dest DIR2
        # pilot copies: every input/output base dir set to DIR, files written under DIR2
        # (DIR2/<campaign>/ttbar/v23/*.yaml); nothing else differs from the production configs.
Run scripts/cli/verify_config_intent.py on every output afterwards.
"""
import argparse
import os
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
C = REPO / "configs_production"
PUB = "/global/cfs/cdirs/m4958/data/ColliderML/simulation"
ST = "/global/cfs/cdirs/m4958/data/ColliderML/staging/simulation"

# (source, destination, kind)
JOBS = [
    ("hard_scatter/ttbar/v20/digitization_config.yaml", "hard_scatter/ttbar/v23/digitization_config.yaml", "tracking"),
    ("hard_scatter/ttbar/v22/pandora_reco_config.yaml", "hard_scatter/ttbar/v23/pandora_reco_config.yaml", "pandora"),
    ("hard_scatter/ttbar/v22/reco_tables_config.yaml", "hard_scatter/ttbar/v23/reco_tables_config.yaml", "reco_tables"),
    ("hard_scatter/ttbar/v20/package_parquet_config.yaml", "hard_scatter/ttbar/v23/package_parquet_config.yaml", "package"),
    ("full_pileup/ttbar/v22/digitization_config.yaml", "full_pileup/ttbar/v23/digitization_config.yaml", "tracking"),
    ("full_pileup/ttbar/v22/pandora_reco_config.yaml", "full_pileup/ttbar/v23/pandora_reco_config.yaml", "pandora"),
    ("full_pileup/ttbar/v22/reco_tables_config.yaml", "full_pileup/ttbar/v23/reco_tables_config.yaml", "reco_tables"),
    ("full_pileup/ttbar/v22/package_parquet_config.yaml", "full_pileup/ttbar/v23/package_parquet_config.yaml", "package"),
]

SEED_REPLAY = {
    "hard_scatter": [((0, 7), "ttbar_v20_run{run}")],
    "full_pileup": [((0, 15), "ttbar_v20_run{run}"), ((16, 1562), "ttbar_v22_run{run}")],
}

HEADER = (
    "# ttbar v23 ({pu}): v22 chain rerun from the tracking stage. Seed finder at the detector field\n"
    "# (3 T, seed minPt 0.65 GeV; v20-v22 and Release 1 seeded at the ACTS default 2 T), historical\n"
    "# digitisation seeds, AMVF vertices, shared-hit counts, rows sorted by event_id.\n"
    "# Generated by scripts/production/make_v23_configs.py from {src}.\n"
)

PROVENANCE = {
    "tracking": (
        "provenance:                   # per-run record, scripts/cli/run_provenance.py (via run_stage)\n"
        "  record: true\n"
        "  require_pushed_commit: true  # refuse to run from a dirty tree or an unpushed commit\n"
        "  commit_marker: false         # .git_commit_success is written by package_parquet only\n"
        "  inputs: [edm4hep.root]\n"
        "  outputs: [digi_provenance.json, timing.csv, sim_with_tracks.root, measurements.root, particles.root,\n"
        "            tracksummary_ambi.root, tracksummary_truth.root, performance_vertexing.root,\n"
        "            'tracker_hits/*.parquet', 'tracker_simhits/*.parquet', 'particles/*.parquet',\n"
        "            'tracks/*.parquet', 'truth_tracks/*.parquet']\n"
        "  container_json: digi_provenance.json   # field and seed read-back written inside the container\n"
    ),
    "pandora": (
        "provenance:\n"
        "  record: true\n"
        "  require_pushed_commit: true\n"
        "  commit_marker: false\n"
        "  inputs: [sim_with_tracks.root]\n"
        "  outputs: [pandora_slices.json, 'reco_parts/reco_part_*.root', reco_edm4hep.root]\n"
        "  image_files: [/opt/k4ODD/k4ODD/options/PandoraSettingsCLD.xml,\n"
        "                /opt/k4ODD/k4ODD/options/PandoraLikelihoodData9EBin_zuds200.xml]\n"
        "  container_json: pandora_slices.json    # source entries and return code of every slice attempt\n"
    ),
    "reco_tables": (
        "provenance:\n"
        "  record: true\n"
        "  require_pushed_commit: true\n"
        "  commit_marker: false\n"
        "  inputs: ['reco_parts/reco_part_*.root', reco_edm4hep.root, edm4hep.root]\n"
        "  outputs: ['calo_cells/*.parquet', 'calo_clusters/*.parquet', 'pfos/*.parquet']\n"
    ),
    "package": (
        "provenance:\n"
        "  record: true\n"
        "  require_pushed_commit: true\n"
        "  commit_marker: true          # the only v23 stage that writes .git_commit_success\n"
    ),
}

TRACKING_EXTRA = (
    "seeding_bfield_tesla: 3.0     # ACTS seed finder field = ODD solenoid (v22 and earlier: ACTS default 2 T)\n"
    "seed_min_pt_gev: 0.65         # seed-finder minPt (v23_plan README 5b: recovers the high-pT seeding loss at 3 T)\n"
    "vertexing: true               # AMVF on the ambiguity-resolved tracks -> performance_vertexing.root -> reco/vertices\n"
    "vertexing_write_track_info: true\n"
    "digitization_seed_replay:     # D2: the seed string each run had in the version v23 replaces\n"
    "{replay}"
)


def sub_once(pattern, repl, text, name):
    new, n = re.subn(pattern, repl, text, flags=re.M)
    if n != 1:
        sys.exit(f"{name}: pattern {pattern!r} matched {n} times, expected 1")
    return new


def build(src, dst, kind, base):
    s = (C / src).read_text()
    # Drop every full-line comment of the parent (they describe v20/v22 runs, chunk counts and
    # dates that are wrong for v23); inline comments on settings are kept.
    body = re.sub(r"^[ \t]*#.*\n", "", s, flags=re.M)
    campaign = src.split("/")[0]
    pu = "PU0" if campaign == "hard_scatter" else "PU200"
    t = HEADER.format(pu=pu, src=src) + body
    t = sub_once(r'^version: "v2[02]"$', 'version: "v23"', t, dst)
    for key in ("output_base_dir", "input_base_dir"):
        t = re.sub(rf'^(\s*){key}: "(?:{re.escape(ST)}|{re.escape(PUB)})".*$',
                   lambda m: f'{m.group(1)}{key}: "{base}"', t, flags=re.M)
    for old in (ST, PUB):
        if old != base and f'"{old}"' in t:
            sys.exit(f"{dst}: base path {old} left in config")
    if kind == "tracking":
        if re.search(r"^(seeding_bfield_tesla|seed_min_pt_gev|vertexing|digitization_seed_replay):", t, re.M):
            sys.exit(f"{dst}: a v23 tracking key is already present")
        replay = "".join(
            f"  - {{runs: [{lo}, {hi}], seed_string: \"{tpl}\"}}\n" for (lo, hi), tpl in SEED_REPLAY[campaign]
        )
        extra = TRACKING_EXTRA.format(replay=replay).rstrip("\n")
        t = sub_once(r"^(reco: true)$", lambda m: m.group(1) + "\n" + extra, t, dst)
    if kind == "package":
        # run_stage resolves the version dir (config snapshot, provenance, marker) from
        # common.output_base_dir; without it the site default (the published tree) is used.
        t = sub_once(r"^(common:\n(?:  .*\n)*?)(?=\S|\n)", lambda m: m.group(1) + f'  output_base_dir: "{base}"   # = output_base_dir below (run_stage version dir)\n', t, dst)
        if campaign == "full_pileup":
            t = sub_once(r"^(\s*)n_runs: 1001\b.*$",
                         lambda m: m.group(1) + "n_runs: 1000                 # chunks: events 0-99 ... 99900-99999 (100,000 events)",
                         t, dst)
        t = sub_once(r"^(\s*- pfos\b.*)$",
                     lambda m: m.group(1)
                     + "\n  - generator_particles        # per-run tables linked from v22 (unchanged)"
                     + "\n  - vertices                   # AMVF, from performance_vertexing.root", t, dst)
        t = t.rstrip("\n") + (
            "\nsort_by_event_id: true         # D3: outer rows strictly ascending in event_id\n"
            "shared_hits_from_hit_ids: true # n_shared_hits recomputed per event from hit_ids (ACTS leaves it 0)\n"
        )
    return t.rstrip("\n") + "\n\n" + PROVENANCE[kind]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--apply", action="store_true")
    ap.add_argument("--base", default=ST, help="input/output base dir (default: staging)")
    ap.add_argument("--dest", default=str(C), help="where to write <campaign>/ttbar/v23/*.yaml")
    a = ap.parse_args()
    real = os.path.realpath(a.base)
    if real == PUB or real.startswith(PUB + "/"):
        sys.exit(f"refusing base {a.base}: v23 is produced in staging or a pilot area, never in the published tree")
    dest = Path(a.dest)
    for src, dst, kind in JOBS:
        t = build(src, dst, kind, a.base)
        out = dest / dst
        if out.exists():
            sys.exit(f"refusing to overwrite {out}")
        print(f"{'write' if a.apply else 'would write'} {out}  (from {src})")
        if a.apply:
            out.parent.mkdir(parents=True, exist_ok=True)
            out.write_text(t)


if __name__ == "__main__":
    main()
